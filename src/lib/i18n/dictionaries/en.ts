/**
 * The SHAPE of a dictionary — keys enforced, values are plain strings.
 *
 * Deliberately not `as const`: that would make every value a literal type, so
 * `Dictionary` would demand the exact English text and every translation would
 * fail to compile. Structure is what we want checked here, not content.
 */
export type Dictionary = typeof en;

